import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import { read } from './_util.mjs';
const ctx = { module: { exports: {} } };
vm.runInNewContext(read('academy/assets/academy-hub.js'), ctx);
const { matchesLesson, nextLesson } = ctx.module.exports;
const manifest = { window: {} };
vm.runInNewContext(read('academy/assets/lessons.js'), manifest);
const lessons = manifest.window.ACADEMY_LESSONS, tracks = manifest.window.ACADEMY_TRACKS;
const noCompletions = () => false;
const state = { query: 'סולאר', track: '', status: '' };
assert(lessons.some(l => matchesLesson(l, tracks, state, noCompletions)), 'Hebrew search must match lesson/track titles');
assert(lessons.some(l => matchesLesson(l, tracks, { ...state, query: 'พลังงาน' }, noCompletions)), 'Thai search must work');
assert(!lessons.some(l => matchesLesson(l, tracks, { ...state, query: 'zzzzzzzzzz' }, noCompletions)), 'No-result state must be reachable');
const sales = lessons.filter(l => matchesLesson(l, tracks, { query: '', track: 'sales-bd', status: 'unfinished' }, (t, n) => t === 'sales-bd' && n === 1));
assert.equal(sales.length, 3, 'Track and completion filters must intersect');
assert.equal(nextLesson(lessons, null, noCompletions).slug, 'solar-fundamentals-01');
assert.equal(nextLesson(lessons, { courseId: 'sales-bd', lessonNum: 2 }, noCompletions).slug, 'sales-bd-02', 'Resume unfinished last lesson');
assert.equal(nextLesson(lessons, { courseId: 'sales-bd', lessonNum: 2 }, (t, n) => t === 'sales-bd' && n === 2).slug, 'sales-bd-03', 'Continue the same track after completion');
assert.equal(nextLesson(lessons, { courseId: 'unknown', lessonNum: 99 }, noCompletions).slug, 'solar-fundamentals-01', 'Invalid stored last lesson must not create a broken link');
assert(nextLesson(lessons, null, () => true), 'All-completed state should offer review');
console.log('hub-discovery: multilingual search, combined filters, resume, next lesson and review passed');
